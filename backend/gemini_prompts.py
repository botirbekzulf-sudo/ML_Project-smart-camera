# Используется в /api/gemini-vision (backend/app.py): Gemini анализирует
# кадр с камеры сканера и коротко описывает, что на нём за устройство.
# Ответ идёт ПРЯМО на сайт (в карточку "Что видит Gemini"), поэтому пиши
# его так, будто это реплика ассистента для пользователя, а не разметка.
DEVICE_PHOTO_PROMPT = """\
Ты — ассистент сканера сайта DevicePrice. Пользователь навёл камеру на
электронное устройство (смартфон, ноутбук, ПК, планшет, умные часы,
монитор, консоль и т.п.).

Посмотри на фото и одним-двумя короткими предложениями скажи:
1) что это за устройство (категория и, если узнаёшь модель/бренд — назови);
2) на какие заметные внешние признаки ты опираешься (форма, экран,
   камеры, логотип и т.п.).

Если на фото не видно электроники — так и скажи одной фразой ("Не вижу
техники в кадре") и не выдумывай устройство.

Отвечай кратко, как реплику для пользователя, без списков и markdown.
"""

# Используется в /api/lookup (backend/app.py): когда у сайта нет доступа
# к платному Google Custom Search API (или пользователь не ввёл
# характеристики вручную), Gemini оценивает типичные параметры
# устройства по своим знаниям — это и подаётся в ML-модель вместо
# одних значений "по умолчанию". Без этого шага одинаковый набор
# признаков по умолчанию давал бы ОДИН И ТОТ ЖЕ ценовой класс для
# любого названия модели.
#
# Формат ответа ОБЯЗАТЕЛЬНО такой (одна строка, без пояснений):
#   RAM_GB=<число>;BATTERY_MAH=<число>;STORAGE_GB=<число>;CAMERA_MP=<число>
# Если поменяешь формат — поправь разбор в
# gemini_assistant.estimate_device_specs().
DEVICE_SPECS_ESTIMATE_PROMPT = """\
Ты — помощник сайта DevicePrice, который оценивает типичные технические
характеристики устройства по его названию, используя свои знания о
существующих моделях техники.

Устройство: "{query}"

Дай свою лучшую оценку четырёх параметров этого устройства (если это
конкретная известная модель — используй её реальные характеристики;
если модель тебе не знакома — дай разумную оценку по классу/линейке
устройства, но НЕ отказывайся отвечать):
- RAM_GB: оперативная память в гигабайтах
- BATTERY_MAH: ёмкость батареи в мА·ч
- STORAGE_GB: встроенная память в гигабайтах
- CAMERA_MP: разрешение основной камеры в мегапикселях

Ответь СТРОГО одной строкой в формате (без пробелов вокруг знаков,
без пояснений до или после):
RAM_GB=<число>;BATTERY_MAH=<число>;STORAGE_GB=<число>;CAMERA_MP=<число>
"""
